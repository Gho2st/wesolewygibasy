/* ---------- pomocnicze ---------- */

const toNumber = (value) =>
  Number(
    String(value)
      .replace(/[^\d,.-]/g, "")
      .replace(",", "."),
  ) || 0;

export const formatPln = (value) =>
  `${new Intl.NumberFormat("pl-PL").format(value)} zł`;

/**
 * Liczy wszystko, co pokazuje sekcja promocyjna, wprost z tabeli cennika.
 * Zmienisz kwoty w PRICING_DATA — sekcja na podstronie zmieni się sama.
 */
export function getPricingSummary(locationId) {
  const data = PRICING_DATA.find((item) => item.id === locationId);
  if (!data) return null;

  const columnIndex = (needle) =>
    data.headers.findIndex((header) =>
      header.toLowerCase().includes(needle.toLowerCase()),
    );

  const column = (index) =>
    index === -1 ? [] : data.rows.map((row) => toNumber(row[index]));

  const feeColumn = column(columnIndex("czesne"));
  const cityColumn = column(columnIndex("u.m"));
  const maluchColumn = column(columnIndex("maluch"));
  const zusColumn = column(columnIndex("aktywnie"));
  const finalColumn = column(columnIndex("ostateczne"));

  const fee = Math.max(...feeColumn);
  const minFinal = Math.min(...finalColumn);
  const maxFinal = Math.max(...finalColumn);

  const sources = [];

  if (cityColumn.length) {
    sources.push({
      key: "miasto",
      icon: "🏛️",
      title: "Dotacja Urzędu Miasta Krakowa",
      amount: "3,50 zł / godz.",
      desc: "Za każdą godzinę opieki nad dzieckiem zamieszkałym w Krakowie. Obniża czesne od razu na fakturze — nie musisz o nic wnioskować.",
      note: `W tym cenniku: ${formatPln(
        Math.min(...cityColumn),
      )}–${formatPln(Math.max(...cityColumn))} miesięcznie.`,
    });
  }

  if (maluchColumn.length) {
    sources.push({
      key: "maluch",
      icon: "🧸",
      title: "Maluch+ 2022–2029",
      amount: `${formatPln(Math.max(...maluchColumn))} / mies.`,
      desc: "Dofinansowanie z programu rządowego. Rozliczamy je za Ciebie — kwota jest już uwzględniona w cenniku.",
    });
  }

  if (zusColumn.length) {
    sources.push({
      key: "zus",
      icon: "👶",
      title: "Aktywnie w żłobku",
      amount: `do ${formatPln(Math.max(...zusColumn))} / mies.`,
      desc: "Świadczenie z ZUS. Zwracane ok. 20. dnia następnego miesiąca (np. za lipiec — ok. 20 sierpnia).",
    });
  }

  return {
    ...data,
    meta: LOCATION_META[locationId] ?? {},
    fee,
    minFinal,
    maxFinal,
    covered: fee - minFinal,
    isFree: maxFinal === 0,
    hasRange: minFinal !== maxFinal,
    sources,
  };
}
